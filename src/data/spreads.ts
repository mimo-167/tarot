export const getSpread = (id: string) => spreads.find((spread) => spread.id === id);

export function localizeSpread(spread: Spread, locale: Locale): LocalizedSpread {
  const english = locale === "en";
  return {
    id: spread.id,
    name: english ? spread.nameEn : spread.name,
    eyebrow: english ? spread.eyebrowEn : spread.eyebrow,
    description: english ? spread.descriptionEn : spread.description,
    positions: english ? spread.positionsEn : spread.positions,
    needsOptions: spread.needsOptions,
    category: categoryLabels[locale][spread.category],
  };
}
